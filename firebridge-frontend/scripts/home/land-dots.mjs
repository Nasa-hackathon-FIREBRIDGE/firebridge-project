// Builds the home page globe's land mask: an equal-area grid of points over the Earth, kept where
// they fall on land in public/places/countries.json, packed as base64 Int16 (lon, lat × 10).
//
//   node scripts/home/land-dots.mjs
//
// Output: src/pages/home/landDots.ts (a few kilobytes instead of the 1.4 MB boundary file).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const STEP = 1.25 // degrees of latitude between rows; longitude spacing widens with latitude

const world = JSON.parse(readFileSync(join(root, 'public/places/countries.json'), 'utf8'))
const polygons = []
for (const feature of world.features) {
  const geometry = feature.geometry
  const list = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  for (const rings of list) {
    let [x0, y0, x1, y1] = [180, 90, -180, -90]
    for (const [x, y] of rings[0]) {
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y)
    }
    polygons.push({ rings, box: [x0, y0, x1, y1] })
  }
}

function inRing(x, y, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

function onLand(x, y) {
  for (const { rings, box } of polygons) {
    if (x < box[0] || x > box[2] || y < box[1] || y > box[3]) continue
    if (inRing(x, y, rings[0]) && !rings.slice(1).some((hole) => inRing(x, y, hole))) return true
  }
  return false
}

const points = []
for (let lat = -90 + STEP / 2; lat < 90; lat += STEP) {
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP))
  const offset = (Math.round((lat + 90) / STEP) % 2) * 0.5 // stagger rows for a woven look
  for (let k = 0; k < count; k++) {
    const lon = -180 + ((k + offset) * 360) / count
    if (onLand(lon, lat)) points.push(Math.round(lon * 10), Math.round(lat * 10))
  }
}

const buffer = Buffer.from(new Int16Array(points).buffer)
const out = `// Generated by scripts/home/land-dots.mjs from public/places/countries.json. Do not edit by hand.
/** Land points of the home page globe: base64 Int16 pairs (longitude, latitude) × 10, ${points.length / 2} points on a ${STEP}° equal-area grid. */
export const LAND_DOTS = '${buffer.toString('base64')}'
`
writeFileSync(join(root, 'src/pages/home/landDots.ts'), out)
console.log(`${points.length / 2} land points, ${(out.length / 1024).toFixed(1)} KB`)
